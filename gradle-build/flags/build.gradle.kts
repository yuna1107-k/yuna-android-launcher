import java.util.Properties

// Generates Flags / FeatureFlags / FeatureFlagsImpl classes from the aconfig declarations,
// standing in for Soong's java_aconfig_library.
// Every flag is false unless set to true in flag_overrides.properties
// (key: "<package>.<flag_name>").
plugins {
    `java-library`
}

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

val aconfigDir = rootProject.file("external/aconfig")
val overridesFile = file("flag_overrides.properties")
val genDir = layout.buildDirectory.dir("generated/aconfig")

val generateFlags by tasks.registering {
    inputs.dir(aconfigDir)
    inputs.file(overridesFile)
    outputs.dir(genDir)
    doLast {
        val overrides = Properties().apply { overridesFile.reader().use { load(it) } }
        val out = genDir.get().asFile
        out.deleteRecursively()

        // package -> ordered flag names
        val flagsByPackage = sortedMapOf<String, MutableSet<String>>()
        aconfigDir.listFiles { f -> f.extension == "aconfig" }!!.sorted().forEach { file ->
            var pkg: String? = null
            var inFlag = false
            file.readLines().forEach { line ->
                val t = line.trim()
                Regex("""^package:\s*"([^"]+)"""").find(t)?.let { pkg = it.groupValues[1] }
                if (Regex("""^flag\s*\{""").containsMatchIn(t)) inFlag = true
                if (inFlag) {
                    Regex("""^name:\s*"([^"]+)"""").find(t)?.let {
                        flagsByPackage.getOrPut(pkg!!) { linkedSetOf() }.add(it.groupValues[1])
                        inFlag = false
                    }
                }
            }
        }

        fun camel(s: String) = s.split('_').mapIndexed { i, p ->
            if (i == 0) p else p.replaceFirstChar { it.uppercase() }
        }.joinToString("")

        flagsByPackage.forEach { (pkg, names) ->
            val dir = File(out, pkg.replace('.', '/')).apply { mkdirs() }
            val header = "// Generated by gradle-build/flags. Do not edit.\npackage $pkg;\n\n"
            File(dir, "Flags.java").writeText(buildString {
                append(header).append("public final class Flags {\n")
                names.forEach { append("    public static final String FLAG_${it.uppercase()} = \"$pkg.$it\";\n") }
                append("\n    private static FeatureFlags FEATURE_FLAGS = new FeatureFlagsImpl();\n\n")
                names.forEach {
                    append("    public static boolean ${camel(it)}() { return FEATURE_FLAGS.${camel(it)}(); }\n")
                }
                append("}\n")
            })
            File(dir, "FeatureFlags.java").writeText(buildString {
                append(header).append("public interface FeatureFlags {\n")
                names.forEach { append("    boolean ${camel(it)}();\n") }
                append("}\n")
            })
            File(dir, "FeatureFlagsImpl.java").writeText(buildString {
                append(header).append("public final class FeatureFlagsImpl implements FeatureFlags {\n")
                names.forEach {
                    val v = overrides.getProperty("$pkg.$it")?.trim()?.toBoolean() ?: false
                    append("    @Override public boolean ${camel(it)}() { return $v; }\n")
                }
                append("}\n")
            })
        }
    }
}

sourceSets.main { java.srcDir(generateFlags) }
